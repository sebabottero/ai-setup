"""Layers: the composed policy loses no rule, core stays generic, profiles install only what they name.
The layers used here are fixtures (tests/fixtures/layers: `me` and `work`), loaded through --layers-dir."""
import fnmatch, json, os, re, shutil, subprocess, sys, tempfile, unittest

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
FIXTURES = os.path.join(ROOT, "tests", "fixtures", "layers")
sys.path.insert(0, os.path.join(ROOT, "core", "guard"))
import guard, layers

GLOB_KEYS = {"ask_commands", "ask_mcp_tools"}  # entries may be covered by a broader glob in another layer


def covered(key, item, composed_items):
    return item in composed_items or (key in GLOB_KEYS and any(fnmatch.fnmatchcase(item, p) for p in composed_items))


def missing(before, after, path=""):
    """Rules of `before` that `after` no longer has."""
    lost = []
    for key, value in before.items():
        if key.startswith("_"):
            continue
        if key not in after:
            lost.append(path + key)
        elif isinstance(value, dict):
            lost += missing(value, after[key], path + key + ".")
        elif isinstance(value, list):
            lost += [f"{path}{key}: {i}" for i in value if not covered(key, i, after[key])]
        elif value is True and after[key] is not True:
            lost.append(path + key)
    return lost


def run(home, build, *extra):
    return subprocess.run([sys.executable, "-I", os.path.join(ROOT, "install.py"), "--home", home, "--build", build,
                           "--tools", "claude,opencode,codex", "--layers-dir", FIXTURES, *extra], capture_output=True, text=True)


class WithFixtureLayers(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        layers.set_extra_roots([FIXTURES])

    @classmethod
    def tearDownClass(cls):
        layers.set_extra_roots([])


class Policy(WithFixtureLayers):
    def test_allow_never_overlaps_ask(self):
        policy = layers.compose_policy(ROOT, layers.present(ROOT))
        asks = policy["ask_commands"]
        for allow in policy["allow_commands"]:
            self.assertNotIn(allow, asks)
        for ask in asks:  # an ask may carve out of a wider allow (git diff * vs --output), but must still prompt
            self.assertEqual(self.decide(policy, ask.replace("*", "x")), "ask", ask)
        for tool in policy["allow_mcp_tools"]:
            self.assertNotIn(tool, policy["ask_mcp_tools"])
            self.assertNotIn("*", tool)

    def test_every_allowed_command_passes_the_guard(self):
        policy = layers.compose_policy(ROOT, layers.present(ROOT))
        for allow in policy["allow_commands"]:
            self.assertEqual(self.decide(policy, allow.replace("*", "x")), "allow", allow)

    def test_tea_reads_are_not_asked(self):
        work = layers.compose_policy(ROOT, ["core", "work"])
        for c in ["tea pulls list", "tea issues view 3", "tea whoami"]:
            self.assertFalse(any(fnmatch.fnmatchcase(c, a) for a in work["ask_commands"]), c)
        for c in ["tea pulls create", "tea issues close 3", "tea comment 4 hi", "tea pr merge 2", "tea api -X POST x",
                  "tea login add"]:
            self.assertTrue(any(fnmatch.fnmatchcase(c, a) for a in work["ask_commands"]), c)

    def test_install_drops_rules_it_no_longer_generates(self):
        home, build = tempfile.mkdtemp(), tempfile.mkdtemp()
        try:
            self.assertEqual(run(home, build).returncode, 0)
            claude, opencode = (os.path.join(home, p) for p in (".claude/settings.json", ".config/opencode/opencode.json"))
            with open(os.path.join(home, ".ai-setup-profile")) as f:
                profile = json.load(f)
            # pretend an older run generated these, and the user added one by hand
            profile["managed"]["claude"]["permissions/ask"].append("Bash(old-rule *)")
            profile["managed"]["opencode"].append({"action": "bash", "resource": "old *", "effect": "ask"})
            with open(os.path.join(home, ".ai-setup-profile"), "w") as f:
                json.dump(profile, f)
            with open(claude) as f:
                settings = json.load(f)
            settings["permissions"]["ask"] += ["Bash(old-rule *)", "Bash(mine *)"]
            with open(claude, "w") as f:
                json.dump(settings, f)
            with open(opencode) as f:
                config = json.load(f)
            config["permissions"].append({"action": "bash", "resource": "old *", "effect": "ask"})
            with open(opencode, "w") as f:
                json.dump(config, f)

            self.assertEqual(run(home, build).returncode, 0)
            with open(claude) as f:
                ask = json.load(f)["permissions"]["ask"]
            self.assertNotIn("Bash(old-rule *)", ask)
            self.assertIn("Bash(mine *)", ask)  # not generated by ai-setup: left alone
            with open(opencode) as f:
                self.assertNotIn({"action": "bash", "resource": "old *", "effect": "ask"}, json.load(f)["permissions"])
        finally:
            shutil.rmtree(home, ignore_errors=True)
            shutil.rmtree(build, ignore_errors=True)

    def test_opencode_allows_stay_before_asks(self):
        home, build = tempfile.mkdtemp(), tempfile.mkdtemp()
        try:
            opencode = os.path.join(home, ".config", "opencode", "opencode.json")
            os.makedirs(os.path.dirname(opencode))
            ask = {"action": "bash", "resource": "git diff *--output*", "effect": "ask"}
            with open(opencode, "w") as f:
                json.dump({"permissions": [ask]}, f)  # an ask from an older run, already in the file
            self.assertEqual(run(home, build).returncode, 0)
            with open(opencode) as f:
                rules = json.load(f)["permissions"]
            allow = {"action": "bash", "resource": "git diff *", "effect": "allow"}
            self.assertLess(rules.index(allow), rules.index(ask))  # the last match wins, so the ask must come after
        finally:
            shutil.rmtree(home, ignore_errors=True)
            shutil.rmtree(build, ignore_errors=True)

    def test_installer_writes_allow_rules(self):
        home, build = tempfile.mkdtemp(), tempfile.mkdtemp()
        try:
            self.assertEqual(run(home, build).returncode, 0)
            with open(os.path.join(home, ".claude", "settings.json")) as f:
                perms = json.load(f)["permissions"]
            self.assertIn("Bash(git status *)", perms["allow"])
            self.assertIn("mcp__atlassian__getJiraIssue", perms["allow"])
            self.assertNotIn("Bash(tea *)", perms["ask"])
            self.assertFalse(set(perms["allow"]) & set(perms["ask"]))
        finally:
            shutil.rmtree(home, ignore_errors=True)
            shutil.rmtree(build, ignore_errors=True)

    def decide(self, policy, command):
        return guard.decide({"tool": "bash", "command": command, "cwd": "/tmp"}, policy)[0]

    def test_core_alone_asks_for_git_and_github_writes(self):
        core = layers.compose_policy(ROOT, ["core"])
        for c in ["git commit -m x", "git push", "gh pr create", "gh issue comment 1 -b x", "rm -rf src"]:
            self.assertEqual(self.decide(core, c), "ask", c)
        self.assertEqual(self.decide(core, "git status"), "allow")

    def test_work_tools_ask_only_with_work(self):
        core = layers.compose_policy(ROOT, ["core"])
        work = layers.compose_policy(ROOT, ["core", "work"])
        for c in ["az repos pr create --title x", "az boards work-item update", "tea pr create"]:
            self.assertEqual(self.decide(work, c), "ask", c)
            self.assertEqual(self.decide(core, c), "allow", c)  # without the work layer these tools are not part of the setup
        self.assertEqual(guard.decide({"tool": "mcp", "name": "atlassian.createJiraIssue"}, work)[0], "ask")
        self.assertEqual(guard.decide({"tool": "mcp", "name": "atlassian.getJiraIssue"}, work)[0], "allow")

    def test_layer_cannot_remove_a_rule(self):
        merged = layers.merge_policies([{"ask_commands": ["a"], "x": True}, {"ask_commands": ["b"], "x": False}])
        self.assertEqual(merged, {"ask_commands": ["a", "b"], "x": True})


class Discovery(unittest.TestCase):
    def test_any_folder_with_layer_content_is_a_layer(self):
        root = tempfile.mkdtemp()
        for path in ["core/policy.json", "php/policy.json", "acme/skills/x/SKILL.md", "personal/AGENTS.md",
                     "docs/AGENTS.md", "tests/policy.json", "_hidden/policy.json", "empty/readme.txt", "Bad/policy.json"]:
            os.makedirs(os.path.dirname(os.path.join(root, path)), exist_ok=True)
            open(os.path.join(root, path), "w").close()
        self.assertEqual(layers.present(root), ["core", "personal", "acme", "php"])  # core, personal, then alphabetical

    def test_new_layer_installs_with_flags_and_uninstalls(self):
        repo = tempfile.mkdtemp()
        keep = shutil.ignore_patterns("build", ".git", "__pycache__", "docs", "*.pdf")
        for item in ("core", "adapters", "install.py"):
            src = os.path.join(ROOT, item)
            (shutil.copytree(src, os.path.join(repo, item), ignore=keep) if os.path.isdir(src)
             else shutil.copy(src, os.path.join(repo, item)))
        os.makedirs(os.path.join(repo, "php", "skills", "composer-check"))
        with open(os.path.join(repo, "php", "skills", "composer-check", "SKILL.md"), "w") as f:
            f.write("---\nname: composer-check\ndescription: test\n---\nbody\n")
        with open(os.path.join(repo, "php", "policy.json"), "w") as f:
            json.dump({"sandbox": {"allowed_domains": ["packagist.org"], "allow_write": ["~/.composer"]}}, f)
        home, build = tempfile.mkdtemp(), tempfile.mkdtemp()

        def go(*extra):
            return subprocess.run([sys.executable, "-I", os.path.join(repo, "install.py"), "--home", home, "--build", build,
                                   "--tools", "claude", *extra], capture_output=True, text=True)

        self.assertEqual(go("--only", "core").returncode, 0)  # a layer that appears later is not installed unasked
        self.assertFalse(os.path.lexists(os.path.join(home, ".claude", "skills", "composer-check")))
        out = go("--with", "php")
        self.assertEqual(out.returncode, 0, out.stderr)
        self.assertTrue(os.path.islink(os.path.join(home, ".claude", "skills", "composer-check")))
        with open(os.path.join(home, ".claude", "settings.json")) as f:
            box = json.load(f)["sandbox"]
        self.assertIn("packagist.org", box["network"]["allowedDomains"])
        self.assertIn("~/.composer", box["filesystem"]["allowWrite"])
        self.assertEqual(go("--uninstall", "php").returncode, 0)
        self.assertFalse(os.path.lexists(os.path.join(home, ".claude", "skills", "composer-check")))
        with open(os.path.join(home, ".claude", "settings.json")) as f:
            self.assertNotIn("packagist.org", json.load(f)["sandbox"]["network"]["allowedDomains"])
        self.assertNotEqual(go("--only", "nonsense").returncode, 0)


class ExternalLayers(unittest.TestCase):
    """Layers can live in another folder (--layers-dir): the engine is public, the private layers sit beside it."""

    def setUp(self):
        self.extra = tempfile.mkdtemp()
        os.makedirs(os.path.join(self.extra, "acme", "skills", "acme-check"))
        os.makedirs(os.path.join(self.extra, "acme", "notes"))
        with open(os.path.join(self.extra, "acme", "skills", "acme-check", "SKILL.md"), "w") as f:
            f.write("---\nname: acme-check\ndescription: test\n---\nbody\n")
        with open(os.path.join(self.extra, "acme", "AGENTS.md"), "w") as f:
            f.write("ACME RULE")
        with open(os.path.join(self.extra, "acme", "notes", "repo.md"), "w") as f:
            f.write("notes")
        with open(os.path.join(self.extra, "acme", "policy.json"), "w") as f:
            json.dump({"ask_commands": ["acme deploy*"]}, f)
        self.home, self.build = tempfile.mkdtemp(), tempfile.mkdtemp()

    def tearDown(self):
        for d in (self.extra, self.home, self.build):
            shutil.rmtree(d, ignore_errors=True)

    def go(self, *extra):
        return run(self.home, self.build, *extra)

    def test_present_and_compose_read_the_extra_folder(self):
        layers.set_extra_roots([self.extra])
        try:
            self.assertIn("acme", layers.present(ROOT))
            self.assertIn("ACME RULE", layers.compose_agents_md(ROOT, ["core", "acme"]))
            self.assertIn("acme deploy*", layers.compose_policy(ROOT, ["core", "acme"])["ask_commands"])
        finally:
            layers.set_extra_roots([])

    def test_extra_folder_cannot_shadow_core(self):
        os.makedirs(os.path.join(self.extra, "core"))
        with open(os.path.join(self.extra, "core", "AGENTS.md"), "w") as f:
            f.write("EVIL")
        layers.set_extra_roots([self.extra])
        try:
            self.assertEqual(layers.layer_dir(ROOT, "core"), os.path.join(ROOT, "core"))
        finally:
            layers.set_extra_roots([])

    def test_install_remember_and_uninstall(self):
        out = self.go("--layers-dir", self.extra, "--with", "acme")
        self.assertEqual(out.returncode, 0, out.stderr)
        link = os.path.join(self.home, ".claude", "skills", "acme-check")
        self.assertEqual(os.path.realpath(link), os.path.realpath(os.path.join(self.extra, "acme", "skills", "acme-check")))
        self.assertTrue(os.path.islink(os.path.join(self.home, "ai-notes", "repo.md")))
        with open(os.path.join(self.build, "AGENTS.md")) as f:
            self.assertIn("ACME RULE", f.read())
        out = self.go()  # the folder is remembered in the profile: no flag needed the next time
        self.assertEqual(out.returncode, 0, out.stderr)
        self.assertTrue(os.path.islink(link))
        self.assertEqual(self.go("--uninstall", "acme").returncode, 0)
        self.assertFalse(os.path.lexists(link))
        self.assertFalse(os.path.lexists(os.path.join(self.home, "ai-notes", "repo.md")))

    def test_layer_placeholder_resolves_to_the_layer_folder(self):
        real = os.path.realpath(self.extra)
        with open(os.path.join(self.extra, "acme", "AGENTS.md"), "w") as f:
            f.write("rules in {{LAYER}}/skills and engine in {{AI_SETUP}}")
        os.makedirs(os.path.join(self.extra, "acme", "agents"))
        with open(os.path.join(self.extra, "acme", "agents", "acme-agent.md"), "w") as f:
            f.write("---\nname: acme-agent\ndescription: d\nmode: subagent\nedit: none\nbash: read-only\n"
                    "claude_tools: Read\ntier: fast\ncolor: red\n---\nsee {{LAYER}}/notes\n")
        self.assertEqual(self.go("--layers-dir", self.extra, "--with", "acme").returncode, 0)
        with open(os.path.join(self.build, "AGENTS.md")) as f:
            text = f.read()
        self.assertIn(f"rules in {real}/acme/skills", text)
        self.assertNotIn("{{LAYER}}", text)
        self.assertIn(f"engine in {ROOT}", text)
        with open(os.path.join(self.home, ".claude", "agents", "acme-agent.md")) as f:
            self.assertIn(f"see {real}/acme/notes", f.read())

    def test_dev_root_moves_notes_and_the_dev_placeholder(self):
        with open(os.path.join(self.extra, "acme", "policy.json"), "w") as f:
            json.dump({"dev_root": "~/Dev"}, f)
        with open(os.path.join(self.extra, "acme", "AGENTS.md"), "w") as f:
            f.write("notes in {{DEV}}/ai-notes")
        self.assertEqual(self.go("--layers-dir", self.extra, "--with", "acme").returncode, 0)
        self.assertTrue(os.path.islink(os.path.join(self.home, "Dev", "ai-notes", "repo.md")))
        self.assertFalse(os.path.lexists(os.path.join(self.home, "ai-notes")))
        with open(os.path.join(self.build, "AGENTS.md")) as f:
            self.assertIn("notes in ~/Dev/ai-notes", f.read())
        self.assertEqual(self.go("--uninstall", "acme").returncode, 0)
        self.assertFalse(os.path.lexists(os.path.join(self.home, "Dev", "ai-notes", "repo.md")))

    def test_policy_of_external_layers_is_protected(self):
        real = os.path.realpath(self.extra)
        layers.set_extra_roots([self.extra])
        try:
            self.assertIn(f"{real}/*/policy.json", layers.compose_policy(ROOT, ["core", "acme"])["protected_paths"])
        finally:
            layers.set_extra_roots([])
        self.assertEqual(self.go("--layers-dir", self.extra, "--with", "acme").returncode, 0)
        with open(os.path.join(self.home, ".claude", "settings.json")) as f:
            asks = json.load(f)["permissions"]["ask"]
        self.assertTrue([a for a in asks if a.startswith("Edit(") and real in a and a.endswith("policy.json)")], asks)

    def test_meta_setup_may_edit_the_external_layers(self):
        real = os.path.realpath(self.extra)
        self.assertEqual(self.go("--layers-dir", self.extra, "--with", "acme").returncode, 0)
        with open(os.path.join(self.home, ".claude", "agents", "meta-setup.md")) as f:
            self.assertIn(f"`{real}/*`", f.read())

    def test_install_refuses_a_policy_where_allow_overlaps_ask(self):
        os.makedirs(os.path.join(self.extra, "bad"))
        with open(os.path.join(self.extra, "bad", "policy.json"), "w") as f:
            json.dump({"allow_commands": ["bad deploy*"], "ask_commands": ["bad deploy*"]}, f)
        out = self.go("--layers-dir", self.extra, "--with", "bad")
        self.assertNotEqual(out.returncode, 0)
        self.assertIn("bad deploy", out.stderr)
        self.assertFalse(os.path.exists(os.path.join(self.home, ".claude", "settings.json")))  # nothing was installed

    def test_missing_folder_fails_clearly(self):
        out = self.go("--layers-dir", os.path.join(self.extra, "nope"))
        self.assertNotEqual(out.returncode, 0)
        self.assertIn("--layers-dir", out.stderr)


class CoreIsGeneric(unittest.TestCase):
    def test_no_work_or_personal_names_in_core(self):
        banned = re.compile(r"dotnet|nuget|/Users/|appsettings|usersecrets|jira|confluence|atlassian|gitea|\btea\b|\baz\b", re.I)
        hits = []
        for base in ("core", "adapters"):
            for dirpath, dirs, files in os.walk(os.path.join(ROOT, base)):
                dirs[:] = [d for d in dirs if d != "__pycache__"]
                for f in files:
                    path = os.path.join(dirpath, f)
                    try:
                        with open(path) as fh:
                            text = fh.read()
                    except UnicodeDecodeError:
                        continue
                    hits += [f"{os.path.relpath(path, ROOT)}: {m.group(0)}" for m in banned.finditer(text)]
        # guard.py keeps the read-only exception for `tea list/view`: a work layer asks for `tea *`, the guard decides it
        hits = [h for h in hits if h not in ("core/guard/guard.py: tea",)]
        self.assertEqual(hits, [])


class Profiles(WithFixtureLayers):
    def setUp(self):
        self.home = tempfile.mkdtemp()
        self.build = tempfile.mkdtemp()

    def path(self, *p):
        return os.path.join(self.home, *p)

    def settings(self):
        with open(self.path(".claude", "settings.json")) as f:
            return json.load(f)

    def test_only_core(self):
        out = run(self.home, self.build, "--only", "core")
        self.assertEqual(out.returncode, 0, out.stderr)
        self.assertTrue(os.path.islink(self.path(".claude", "skills", "ticket-flow")))
        self.assertFalse(os.path.lexists(self.path(".claude", "skills", "me-skill")))
        self.assertFalse(os.path.lexists(self.path("ai-notes", "work-repo.md")))
        box = self.settings()["sandbox"]
        self.assertNotIn("api.nuget.org", box["network"]["allowedDomains"])
        self.assertNotIn("enableWeakerNetworkIsolation", box)
        with open(os.path.join(self.build, "AGENTS.md")) as f:
            text = f.read()
        self.assertNotIn("test fixture", text)

    def test_with_work_adds_and_is_remembered(self):
        run(self.home, self.build, "--only", "core")
        run(self.home, self.build, "--with", "work")
        self.assertTrue(os.path.islink(self.path("ai-notes", "work-repo.md")))
        self.assertIn("api.nuget.org", self.settings()["sandbox"]["network"]["allowedDomains"])
        self.assertFalse(os.path.lexists(self.path(".claude", "skills", "me-skill")))
        out = run(self.home, self.build)  # no flag: same profile, nothing to change
        self.assertNotRegex(out.stdout, r"(?m)^(write|link|backup|remove) ")
        self.assertIn("layers: core, work", out.stdout)

    def test_narrower_profile_removes_nothing(self):
        run(self.home, self.build)
        out = run(self.home, self.build, "--only", "core")
        self.assertEqual(out.returncode, 0, out.stderr)
        self.assertTrue(os.path.islink(self.path("ai-notes", "work-repo.md")))
        self.assertTrue(os.path.islink(self.path(".claude", "skills", "me-skill")))
        self.assertIn("api.nuget.org", self.settings()["sandbox"]["network"]["allowedDomains"])

    def test_uninstall_work_only(self):
        run(self.home, self.build)
        out = run(self.home, self.build, "--uninstall", "work")
        self.assertEqual(out.returncode, 0, out.stderr)
        self.assertFalse(os.path.lexists(self.path("ai-notes", "work-repo.md")))
        box = self.settings()["sandbox"]
        self.assertNotIn("api.nuget.org", box["network"]["allowedDomains"])
        self.assertNotIn("enableWeakerNetworkIsolation", box)
        self.assertIn("github.com", box["network"]["allowedDomains"])  # core's stay
        self.assertTrue(os.path.islink(self.path(".claude", "skills", "me-skill")))  # me's stay
        self.assertTrue(os.path.isdir(self.path(".ai-setup-backups")))
        with open(self.path(".ai-setup-profile")) as f:
            self.assertEqual(json.load(f)["layers"], ["core", "me"])

    def test_core_cannot_be_uninstalled_and_unknown_layers_fail(self):
        self.assertNotEqual(run(self.home, self.build, "--uninstall", "core").returncode, 0)
        self.assertNotEqual(run(self.home, self.build, "--only", "nonsense").returncode, 0)

    def test_work_needs_core(self):
        run(self.home, self.build, "--only", "work")
        with open(self.path(".ai-setup-profile")) as f:
            self.assertEqual(json.load(f)["layers"], ["core", "work"])


