#!/usr/bin/env python3
"""Install ai-setup into every agent tool found on this machine.

core/      tool-agnostic source: AGENTS.md, agents/, skills/, policy.json, guard/
<layer>/   optional layers with core's shape (agents/, skills/, notes/, policy.json, AGENTS.md). A layer is any folder
           with that content, in this repo or in another one (--layers-dir). Layers only add: install.py composes them
           into build/AGENTS.md and build/policy.json.
adapters/  what makes each tool work best: its own skills/, agents/, hooks, plugins and settings.
           An adapter adds to core and never shadows it: a skill or agent with a core name stops the install.

Edit a layer or adapters/, then run ./install.sh again. Anything this script replaces is copied to
~/.ai-setup-backups/<timestamp>/ first.
Usage: ./install.sh [--dry-run] [--tools claude,opencode,codex] [--home DIR]
                    [--only core,<layer> | --with <layer> | --uninstall <layer>]
                    [--layers-dir DIR]   (folder with more layers, e.g. a private repo; remembered in the profile)
The chosen layers are remembered in ~/.ai-setup-profile; with no flag the last choice is repeated (first time: all).
"""
import argparse, datetime, json, os, re, shutil, sys

ROOT = os.path.dirname(os.path.realpath(__file__))
sys.path.insert(0, os.path.join(ROOT, "core", "guard"))
import layers as layerlib
import guard

CORE = os.path.join(ROOT, "core")
ADAPTERS = os.path.join(ROOT, "adapters")
BUILD = os.path.join(ROOT, "build")
SELECTED = []  # layers being installed; main() fills it from the flags or the saved profile
CLAUDE_MODELS = {"strong": "opus", "balanced": "sonnet", "fast": "haiku"}
COLORS = {"yellow": "#d4a017", "green": "#2e9d5b", "blue": "#3b74e0", "purple": "#8457d6", "red": "#d24545",
          "orange": "#e07b2e", "cyan": "#1f9fb5", "gray": "#7a8494"}
READ_ONLY_BASH = ["git diff*", "git log*", "git show*", "git status*", "ls*", "grep *", "rg *"]
TOOLS = ["claude", "opencode", "codex"]

args = None
HOME = None
STAMP = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")


def log(msg):
    print(("[dry-run] " if args.dry_run else "") + msg)


def backup(path):
    if not os.path.lexists(path):
        return
    dest = os.path.join(HOME, ".ai-setup-backups", STAMP, os.path.relpath(path, HOME))
    log(f"backup  {path} -> {dest}")
    if not args.dry_run:
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        if os.path.islink(path) or os.path.isfile(path):
            shutil.copy2(path, dest, follow_symlinks=False)
        else:
            shutil.copytree(path, dest, symlinks=True)


def remove(path):
    if os.path.islink(path) or os.path.isfile(path):
        os.remove(path)
    elif os.path.isdir(path):
        shutil.rmtree(path)


def link(src, dst):
    if os.path.islink(dst) and os.path.realpath(dst) == os.path.realpath(src):
        return
    backup(dst)
    log(f"link    {dst} -> {src}")
    if not args.dry_run:
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if os.path.lexists(dst):
            remove(dst)
        os.symlink(src, dst)


def write(path, text):
    if os.path.isfile(path) and not os.path.islink(path) and open(path).read() == text:
        return
    backup(path)
    log(f"write   {path}")
    if not args.dry_run:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if os.path.islink(path):
            os.remove(path)
        with open(path, "w") as f:
            f.write(text)


def read_json(path):
    if not os.path.isfile(path):
        return {}
    with open(path) as f:
        return json.load(f)


def add_unique(items, new):
    for item in new:
        if item not in items:
            items.append(item)
    return items


MANAGED = {}  # what this run generated per tool, saved in the profile so the next run can drop what is no longer generated


def previous_managed(tool):
    return read_json(profile_path()).get("managed", {}).get(tool)


def sync_list(items, current, previous, known, ordered=False):
    """Add `current`; drop what a past run generated (`previous`) and no layer on disk generates now (`known`). A narrower
    profile therefore removes nothing, and entries the user added by hand stay. `ordered`: re-append `current` last, in
    order, for lists where the last match wins (OpenCode)."""
    subtract(items, [i for i in previous or [] if i not in known] + (current if ordered else []))
    add_unique(items, current)


MARKER = "<!-- generated by ai-setup: edit <layer>/agents/ -->"
MARKER_PREFIXES = ("<!-- generated by ai-setup", "<!-- generado por ai-setup")  # the second one marks files from older runs


def is_generated(text):
    return any(prefix in text for prefix in MARKER_PREFIXES)


def prune_agents(folder, keep):
    """Remove agent files this installer generated earlier whose source no longer exists in any layer.
    `keep` covers every layer on disk, not just the selected ones: choosing fewer layers removes nothing."""
    if not os.path.isdir(folder):
        return
    for f in os.listdir(folder):
        path = os.path.join(folder, f)
        if f.endswith(".md") and f[:-3] not in keep and os.path.isfile(path) and is_generated(open(path).read()):
            backup(path)
            log(f"remove  {path}")
            if not args.dry_run:
                os.remove(path)


def prune_skills(folder):
    """Remove links to skills that were deleted from core/skills."""
    if not os.path.isdir(folder):
        return
    for name in os.listdir(folder):
        path = os.path.join(folder, name)
        if os.path.islink(path) and os.readlink(path).startswith(tuple(layerlib.roots(ROOT))) and not os.path.exists(path):
            log(f"remove  {path}")
            if not args.dry_run:
                os.remove(path)


def parse_agent(path):
    text = open(path).read()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    meta = dict(line.split(":", 1) for line in m.group(1).splitlines() if ":" in line)
    meta = {k.strip(): v.strip() for k, v in meta.items()}
    return meta, m.group(2).lstrip("\n")


def expand(text):
    text = text.replace("{{AI_SETUP}}", ROOT)
    return HOME + text[1:] if text.startswith("~") else text


def collisions(core_names, adapter_names):
    return sorted(set(core_names) & set(adapter_names))


def layer_bases(kind, layer_names):
    return [os.path.join(layerlib.layer_dir(ROOT, l), kind) for l in layer_names]


def sources(kind, tool, layer_names=None):
    """{name: path} for <layer>/<kind> of the selected layers plus adapters/<tool>/<kind> (kind: skills | agents)."""
    found = {}
    for base in layer_bases(kind, SELECTED if layer_names is None else layer_names) + [os.path.join(ADAPTERS, tool, kind)]:
        if not os.path.isdir(base):
            continue
        names = {}
        for entry in sorted(os.listdir(base)):
            path = os.path.join(base, entry)
            if kind == "skills" and os.path.isfile(os.path.join(path, "SKILL.md")):
                names[entry] = path
            elif kind == "agents" and entry.endswith(".md"):
                names[entry[:-3]] = path
        clash = collisions(found, names)
        if clash:
            sys.exit(f"{os.path.relpath(base, ROOT)} repeats names from another layer or from core: {', '.join(clash)}. "
                     "A layer or adapter adds, it does not replace: rename it or improve the original.")
        found.update(names)
    return found


def edit_globs(glob):
    """One `edit:` entry as globs. {{LAYERS}} stands for every folder given with --layers-dir (none: no entry)."""
    if "{{LAYERS}}" in glob:
        return [expand(glob.replace("{{LAYERS}}", r)) for r in layerlib.EXTRA_ROOTS]
    return [expand(glob)]


def agents(tool):
    """Canonical agents. Frontmatter: name, description, mode (subagent|primary|all), tier (strong|balanced|fast),
    color, claude_tools (comma list or *), edit (none | all | comma list of path globs), bash (read-only | checks | all),
    effort (low | medium | high | xhigh: reasoning effort; Claude applies it, OpenCode ignores it for now)."""
    result = []
    for path in sources("agents", tool).values():
        meta, body = parse_agent(path)
        edit = meta.get("edit", "none")
        meta["edit_globs"] = [] if edit in ("none", "all") else [e for g in edit.split(",") for e in edit_globs(g.strip())]
        folder = os.path.dirname(os.path.dirname(path))  # <layer>/agents/x.md -> the layer's own folder
        result.append((meta, body.replace("{{LAYER}}", folder).replace("{{AI_SETUP}}", ROOT)))
    return result


def skills(tool):
    return sorted(sources("skills", tool).items())


def allow_unsandboxed(pol):
    """True when a command that fails on the sandbox may ask to run outside it (each run still needs the user's OK)."""
    return pol.get("sandbox", {}).get("allow_unsandboxed_commands") is True


def policy(layer_names=None):
    return layerlib.compose_policy(ROOT, SELECTED if layer_names is None else layer_names)


def all_agent_names(tool):
    """Agent names of every layer on disk: what prune keeps, so a narrower profile removes nothing."""
    return set(sources("agents", tool, layerlib.present(ROOT)))


def render_tree(src, dst):
    """Copy a folder replacing {{AI_SETUP}}: for files a tool loads by itself (plugins)."""
    for dirpath, _, files in os.walk(src):
        for f in sorted(files):
            path = os.path.join(dirpath, f)
            write(os.path.join(dst, os.path.relpath(path, src)), open(path).read().replace("{{AI_SETUP}}", ROOT))


def sandbox_paths(pol):
    """Secret files as sandbox globs: anywhere under home."""
    return ["~/**/" + f for f in pol["deny_files"]]


def protected_paths(pol):
    """The setup's own rules (policy, guard, hooks, plugins, installer, tests) as absolute globs."""
    return [expand(p.replace("{{AI_SETUP}}", ROOT)).replace("/*", "/**") for p in pol.get("protected_paths", [])]


def render_build(name, text):
    path = os.path.join(BUILD, name)
    if os.path.isfile(path) and open(path).read() == text:
        return path  # unchanged; Claude's sandbox also protects it, since ~/.claude/CLAUDE.md points here
    log(f"render  {path}")
    if not args.dry_run:
        os.makedirs(BUILD, exist_ok=True)
        with open(path, "w") as f:
            f.write(text)
    return path


def build_agents_md():
    return render_build("AGENTS.md", layerlib.compose_agents_md(ROOT, SELECTED))


def build_policy():
    """build/policy.json: the policy of the selected layers. The guard reads this file at run time."""
    return render_build("policy.json", json.dumps(policy(), indent=2, ensure_ascii=False) + "\n")


def link_notes(layer_names):
    """<layer>/notes/*.md -> ~/ai-notes/: per-repo notes live in ai-setup (and its backup), the tools read them from home."""
    for layer in layer_names:
        folder = os.path.join(layerlib.layer_dir(ROOT, layer), "notes")
        if os.path.isdir(folder):
            for name in sorted(os.listdir(folder)):
                if name.endswith(".md"):
                    link(os.path.join(folder, name), os.path.join(HOME, "ai-notes", name))


UNMANAGED = []  # skills installed straight into a tool, outside core/skills


def adopt_unmanaged(folder):
    """Find skills a tool has that did not come from core/skills. With --adopt, move them into core/skills."""
    if not os.path.isdir(folder):
        return
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if name == "synced" or name.startswith(".") or not os.path.isfile(os.path.join(path, "SKILL.md")):
            continue  # "synced" = skills claude.ai manages itself
        if os.path.islink(path) and os.path.realpath(path).startswith(tuple(layerlib.roots(ROOT))):
            continue
        dest = os.path.join(layerlib.layer_dir(ROOT, args.layer), "skills", name)
        if not args.adopt:
            UNMANAGED.append(path)
        elif os.path.exists(dest):
            log(f"skip    {path}: {args.layer}/skills/{name} already exists; check by hand which one you want")
        else:
            log(f"adopt   {path} -> {dest}")
            if not args.dry_run:
                shutil.copytree(path, dest, symlinks=False, ignore=shutil.ignore_patterns(".git"))


# ---------------------------------------------------------------- Claude Code
def add_hook(settings, event, matcher, script, timeout):
    hook = {"type": "command", "command": f'python3 -I "$HOME/.claude/hooks/{script}"', "timeout": timeout}
    groups = settings.setdefault("hooks", {}).setdefault(event, [])
    if not any(h.get("command") == hook["command"] for g in groups for h in g.get("hooks", [])):
        groups.append({"matcher": matcher, "hooks": [hook]} if matcher else {"hooks": [hook]})


def claude_lists(pol):
    """The settings.json lists a policy contributes: {path of keys: items}. Install adds them; uninstall subtracts."""
    sb = pol.get("sandbox", {})
    secrets = sandbox_paths(pol)
    return {
        ("permissions", "ask"): [f"Bash({c})" for c in pol.get("ask_commands", [])] +
                                ["mcp__" + t.replace(".", "__") for t in pol.get("ask_mcp_tools", []) if "*" not in t] +
                                [f"Edit(/{p})" for p in protected_paths(pol)],  # "//" = absolute path in Claude rules
        # read-only commands and MCP tools that never need a prompt; ask and deny rules still win over these
        ("permissions", "allow"): [f"Bash({c})" for c in pol.get("allow_commands", [])] +
                                  ["mcp__" + t.replace(".", "__") for t in pol.get("allow_mcp_tools", []) if "*" not in t],
        ("permissions", "deny"): [f"{tool}(**/{f})" for f in pol.get("deny_files", []) for tool in ("Read", "Edit")] +
                                 [f"Read({d}/**)" for d in pol.get("deny_home_dirs", [])],
        ("permissions", "additionalDirectories"): [expand(d) for d in pol.get("work_dirs", [])],
        ("sandbox", "excludedCommands"): sb.get("unsandboxed_commands", []),
        ("sandbox", "filesystem", "allowWrite"): sb.get("allow_write", []),
        ("sandbox", "filesystem", "denyRead"): pol.get("deny_home_dirs", []) + secrets,
        ("sandbox", "filesystem", "denyWrite"): protected_paths(pol),
        ("sandbox", "credentials", "files"): [{"path": p, "mode": "deny"} for p in secrets],
        ("sandbox", "network", "allowedDomains"): sb.get("allowed_domains", []),
    }


def install_claude(agents_md):
    base = os.path.join(HOME, ".claude")
    link(agents_md, os.path.join(base, "CLAUDE.md"))
    adopt_unmanaged(os.path.join(base, "skills"))
    for name, src in skills("claude"):
        link(src, os.path.join(base, "skills", name))
    prune_skills(os.path.join(base, "skills"))
    hooks = os.path.join(ADAPTERS, "claude", "hooks")
    for name in sorted(os.listdir(hooks)):
        if name.endswith(".py"):
            link(os.path.join(hooks, name), os.path.join(base, "hooks", name))

    for meta, body in agents("claude"):
        # Claude subagents cannot be path-restricted: edit scope is enforced by the prompt here, by config in OpenCode
        front = [f"name: {meta['name']}", f"description: {meta['description']}"]
        if meta.get("claude_tools", "*") != "*":
            front.append(f"tools: {meta['claude_tools']}")
        front += [f"model: {CLAUDE_MODELS.get(meta.get('tier'), 'inherit')}", f"color: {meta.get('color', 'gray')}"]
        if meta.get("effort"):
            front.append(f"effort: {meta['effort']}")
        if meta["edit_globs"]:
            body = "Only edit files matching: " + ", ".join(f"`{g}`" for g in meta["edit_globs"]) + ".\n\n" + body
        write(os.path.join(base, "agents", meta["name"] + ".md"),
              "---\n" + "\n".join(front) + "\n---\n\n" + MARKER + "\n" + body)

    prune_agents(os.path.join(base, "agents"), all_agent_names("claude"))

    path = os.path.join(base, "settings.json")
    settings = read_json(path)
    before = json.dumps(settings, sort_keys=True)
    for key, value in read_json(os.path.join(ADAPTERS, "claude", "settings.base.json")).items():
        if not key.startswith("_"):
            settings.setdefault(key, value)
    pol = policy()
    perms = settings.setdefault("permissions", {})
    perms.setdefault("defaultMode", "auto")  # a classifier reviews actions; bypass skips every check but the hook
    # subagents without their own model (general-purpose, claude-code-guide) would inherit the strong session model;
    # our agents set `model` in their frontmatter, which wins over this variable
    settings.setdefault("env", {}).setdefault("CLAUDE_CODE_SUBAGENT_MODEL", "sonnet")
    add_hook(settings, "PreToolUse", "Bash|mcp__.*", "policy_guard.py", 10)
    add_hook(settings, "UserPromptSubmit", None, "context_notice.py", 5)  # informational context-size notice

    # OS sandbox for Bash, from the composed policy: the wall the regex guard cannot be
    box = settings.setdefault("sandbox", {})
    for key, value in {"enabled": True, "failIfUnavailable": True, "autoAllowBashIfSandboxed": True}.items():
        box.setdefault(key, value)
    box["allowUnsandboxedCommands"] = allow_unsandboxed(pol)  # off unless a layer opts in: policy "sandbox.allow_unsandboxed_commands"
    previous = previous_managed("claude") or {}
    known = claude_lists(policy(layerlib.present(ROOT)))
    MANAGED["claude"] = {"/".join(k): v for k, v in known.items()}
    for keys, items in claude_lists(pol).items():
        node = settings
        for key in keys[:-1]:
            node = node.setdefault(key, {})
        sync_list(node.setdefault(keys[-1], []), items, previous.get("/".join(keys)), known[keys])
    if pol.get("sandbox", {}).get("weaker_network_isolation"):
        box["enableWeakerNetworkIsolation"] = True
    if json.dumps(settings, sort_keys=True) != before:
        write(path, json.dumps(settings, indent=2, ensure_ascii=False) + "\n")


# ---------------------------------------------------------------- OpenCode
def yaml_str(value):
    return json.dumps(value, ensure_ascii=False)  # JSON strings are valid YAML scalars


def opencode_skill_dirs(layer_names):
    dirs = [d for d in layer_bases("skills", layer_names) if os.path.isdir(d)]
    adapter = os.path.join(ADAPTERS, "opencode", "skills")
    has_adapter_skills = os.path.isdir(adapter) and any(
        os.path.isfile(os.path.join(adapter, n, "SKILL.md")) for n in os.listdir(adapter))
    return dirs + ([adapter] if has_adapter_skills else [])


def opencode_rules(pol):
    """Ordered rules, the last match wins. Plain globs, so "git -C <dir> push" needs its own rule (Claude's hook normalizes it)."""
    asks = pol.get("ask_commands", [])
    commands = asks + ["git -C * " + c[4:] for c in asks if c.startswith("git ")]
    # the last match wins, so the allows come first and every ask after them still prompts
    rules = [{"action": "bash", "resource": c, "effect": "allow"} for c in pol.get("allow_commands", [])]
    rules += [{"action": "bash", "resource": c, "effect": "ask"} for c in commands]
    for f in pol.get("deny_files", []):
        rules += [{"action": a, "resource": "*" + f.lstrip("*"), "effect": "deny"} for a in ("read", "edit")]
    rules += [{"action": "read", "resource": d.replace("~", HOME) + "/*", "effect": "deny"} for d in pol.get("deny_home_dirs", [])]
    rules += [{"action": "external_directory", "resource": expand(d) + "/*", "effect": "allow"} for d in pol.get("work_dirs", [])]
    rules += [{"action": "edit", "resource": p, "effect": "ask"} for p in protected_paths(pol)]
    return rules


def install_opencode(agents_md):
    base = os.path.join(HOME, ".config", "opencode")
    adopt_unmanaged(os.path.join(base, "skills"))
    tiers = read_json(os.path.join(ADAPTERS, "opencode", "tiers.json"))
    pol = policy()

    for meta, body in agents("opencode"):
        lines = ["---", f"description: {yaml_str(meta['description'])}", f"mode: {meta.get('mode', 'subagent')}",
                 f"color: {yaml_str(COLORS.get(meta.get('color'), COLORS['gray']))}"]
        tier = tiers.get("overrides", {}).get(meta["name"], meta.get("tier"))
        if tiers.get(tier):
            lines.append(f"model: {yaml_str(tiers[tier])}")
        # v2 ordered rules, appended after the global ones; the last match wins.
        # (A nested `permission: {bash: {...}}` is ignored in agent files, hence the explicit list.)
        rules = []
        if meta.get("edit", "none") != "all":
            rules.append(("edit", "*", "deny"))
        for glob in meta["edit_globs"]:
            rules.append(("edit", glob, "allow"))
            if glob.startswith("/"):
                rules.append(("external_directory", glob, "allow"))
        if meta["edit_globs"] or meta.get("edit") == "all":  # an agent's allow must not open the setup's own rules
            rules += [("edit", p, "ask") for p in protected_paths(pol)]
        if meta.get("bash") == "read-only":
            rules += [("bash", "*", "ask")] + [("bash", c, "allow") for c in READ_ONLY_BASH]
        elif meta.get("bash") == "checks":  # builds and tests yes, git state changes never
            rules += [("bash", "*", "allow")] + [("bash", c, "deny") for c in pol["ask_commands"] + [
                "git reset*", "git checkout*", "git stash*", "git switch*"]]
        lines.append("permissions:")
        lines += [f"  - {{action: {yaml_str(a)}, resource: {yaml_str(r)}, effect: {yaml_str(e)}}}" for a, r, e in rules]
        lines.append("---")
        write(os.path.join(base, "agents", meta["name"] + ".md"),
              "\n".join(lines) + "\n\n" + MARKER + "\n" + body)

    prune_agents(os.path.join(base, "agents"), all_agent_names("opencode"))

    # a .js file in ~/.config/opencode/plugins/ loads by itself (that is how Orca's status plugin loads)
    plugins = os.path.join(ADAPTERS, "opencode", "plugins")
    if os.path.isdir(plugins):
        render_tree(plugins, os.path.join(base, "plugins"))

    path = os.path.join(base, "opencode.json")
    config = read_json(path)
    before = json.dumps(config, sort_keys=True)
    config.setdefault("$schema", "https://opencode.ai/config.json")
    for key, value in read_json(os.path.join(ADAPTERS, "opencode", "opencode.base.json")).items():
        if not key.startswith("_"):
            config.setdefault(key, value)
    add_unique(config.setdefault("instructions", []), [agents_md])
    skill_dirs = opencode_skill_dirs(SELECTED)
    if isinstance(config.get("skills"), dict):
        add_unique(config["skills"].setdefault("paths", []), skill_dirs)
    else:
        add_unique(config.setdefault("skills", []), skill_dirs)
    rules, known = opencode_rules(pol), opencode_rules(policy(layerlib.present(ROOT)))
    sync_list(config.setdefault("permissions", []), rules, previous_managed("opencode"), known, ordered=True)
    MANAGED["opencode"] = known
    if json.dumps(config, sort_keys=True) != before:
        write(path, json.dumps(config, indent=2, ensure_ascii=False) + "\n")


