# ---------------------------------------------------------------- profile (which layers are installed)
def profile_path():
    return os.path.join(HOME, ".ai-setup-profile")


def saved_layers():
    saved = read_json(profile_path()).get("layers")
    return [l for l in layerlib.present(ROOT) if saved is None or l in saved]  # a new layer is never installed unasked


def parse_layers(text):
    names = [n.strip() for n in text.split(",") if n.strip()]
    unknown = [n for n in names if n not in layerlib.present(ROOT)]
    if unknown:
        sys.exit(f"unknown layer or no folder for it: {', '.join(sorted(unknown))}. "
                 f"Layers: {', '.join(layerlib.present(ROOT))}")
    return names


def resolve_layers():
    """core is always on. --only replaces the profile, --with adds to it, no flag repeats it (first time: all present)."""
    if args.only:
        chosen = parse_layers(args.only)
    elif args.with_:
        chosen = saved_layers() + parse_layers(args.with_)
    else:
        chosen = saved_layers()
    chosen = ["core"] + chosen
    if "core" not in layerlib.present(ROOT):
        sys.exit("the core/ folder is missing: without it there is nothing to install.")
    return [l for l in layerlib.present(ROOT) if l in chosen]


def save_profile():
    if not args.dry_run:
        managed = {**read_json(profile_path()).get("managed", {}), **MANAGED}  # a tool not touched this run keeps its record
        with open(profile_path(), "w") as f:
            json.dump({"layers": SELECTED, "layers_dirs": layerlib.EXTRA_ROOTS, "managed": managed}, f)
            f.write("\n")


# ---------------------------------------------------------------- uninstall one layer
def unlink_layer(removed, tool):
    """Remove from one tool the skill links, generated agents and notes that came from the given layers."""
    prefixes = tuple(layerlib.layer_dir(ROOT, l) + os.sep for l in removed)
    skills_dir = {"claude": ".claude/skills", "codex": ".codex/skills"}.get(tool)
    if skills_dir and os.path.isdir(os.path.join(HOME, skills_dir)):
        for name in sorted(os.listdir(os.path.join(HOME, skills_dir))):
            path = os.path.join(HOME, skills_dir, name)
            if os.path.islink(path) and os.path.realpath(path).startswith(prefixes):
                backup(path)
                log(f"remove  {path}")
                if not args.dry_run:
                    os.remove(path)
    agents_dir = {"claude": ".claude/agents", "opencode": ".config/opencode/agents"}.get(tool)
    if agents_dir:
        names = set(sources("agents", tool, removed))
        for name in sorted(names):
            path = os.path.join(HOME, agents_dir, name + ".md")
            if os.path.isfile(path) and is_generated(open(path).read()):
                backup(path)
                log(f"remove  {path}")
                if not args.dry_run:
                    os.remove(path)


def unlink_notes(removed):
    folder = os.path.join(HOME, "ai-notes")
    for name in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
        path = os.path.join(folder, name)
        if os.path.islink(path) and os.path.realpath(path).startswith(tuple(layerlib.layer_dir(ROOT, l) + os.sep for l in removed)):
            backup(path)
            log(f"remove  {path}")
            if not args.dry_run:
                os.remove(path)


def subtract(items, drop):
    items[:] = [i for i in items if i not in drop]


def uninstall_settings(tool, removed, old_pol, new_pol):
    """Take out the settings entries only the removed layers contributed."""
    if tool == "claude":
        path = os.path.join(HOME, ".claude", "settings.json")
        settings = read_json(path)
        before = json.dumps(settings, sort_keys=True)
        keep = claude_lists(new_pol)
        for keys, items in claude_lists(old_pol).items():
            node = settings
            for key in keys[:-1]:
                node = node.get(key, {})
            if isinstance(node.get(keys[-1]), list):
                subtract(node[keys[-1]], [i for i in items if i not in keep[keys]])
        if old_pol.get("sandbox", {}).get("weaker_network_isolation") and not new_pol.get("sandbox", {}).get("weaker_network_isolation"):
            settings.get("sandbox", {}).pop("enableWeakerNetworkIsolation", None)
        if json.dumps(settings, sort_keys=True) != before:
            write(path, json.dumps(settings, indent=2, ensure_ascii=False) + "\n")
    elif tool == "opencode":
        path = os.path.join(HOME, ".config", "opencode", "opencode.json")
        config = read_json(path)
        before = json.dumps(config, sort_keys=True)
        keep = opencode_rules(new_pol)
        subtract(config.get("permissions", []), [r for r in opencode_rules(old_pol) if r not in keep])
        gone = [d for d in opencode_skill_dirs(removed) if d not in opencode_skill_dirs(SELECTED)]
        skills_cfg = config.get("skills")
        subtract(skills_cfg.get("paths", []) if isinstance(skills_cfg, dict) else skills_cfg or [], gone)
        if json.dumps(config, sort_keys=True) != before:
            write(path, json.dumps(config, indent=2, ensure_ascii=False) + "\n")


def run_uninstall(tools):
    removed = parse_layers(args.uninstall)
    if "core" in removed:
        sys.exit("core cannot be uninstalled: everything else builds on it.")
    old_layers = saved_layers()
    old_pol = policy(old_layers)
    SELECTED[:] = [l for l in old_layers if l not in removed]
    new_pol = policy()
    for tool in tools:
        print(f"\n== {tool}")
        unlink_layer(removed, tool)
        uninstall_settings(tool, removed, old_pol, new_pol)
        if tool == "claude":
            MANAGED["claude"] = {"/".join(k): v for k, v in claude_lists(new_pol).items()}
        elif tool == "opencode":
            MANAGED["opencode"] = opencode_rules(new_pol)
    unlink_notes(removed)
    build_agents_md()
    build_policy()
    save_profile()


def lint_policy(pol):
    """Problems in the composed policy of the chosen layers, checked before anything is written: a layer outside this repo
    is not covered by the tests, so the installer checks the same invariants. Returns a list of messages."""
    problems = []
    asks = pol.get("ask_commands", [])

    def decide(command):
        return guard.decide({"tool": "bash", "command": command, "cwd": "/tmp"}, pol)[0]

    for allow in pol.get("allow_commands", []):
        if allow in asks:
            problems.append(f"allow_commands and ask_commands both list '{allow}'")
        elif decide(allow.replace("*", "x")) != "allow":
            problems.append(f"allow_commands '{allow}' does not run without asking: another rule wins")
    for ask in asks:
        if decide(ask.replace("*", "x")) not in ("ask", "deny"):
            problems.append(f"ask_commands '{ask}' would not ask: it is allowed by another rule")
    for tool in pol.get("allow_mcp_tools", []):
        if tool in pol.get("ask_mcp_tools", []):
            problems.append(f"allow_mcp_tools and ask_mcp_tools both list '{tool}'")
        if "*" in tool:
            problems.append(f"allow_mcp_tools '{tool}': no wildcards, list each read-only tool")
    return problems


def detected():
    found = []
    for tool, conf in [("claude", ".claude"), ("opencode", ".config/opencode"), ("codex", ".codex")]:
        if shutil.which(tool) or os.path.isdir(os.path.join(HOME, conf)):
            found.append(tool)
    return found


def main():
    global args, HOME, BUILD
    p =argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dry-run", action="store_true", help="show what would change, change nothing")
    p.add_argument("--tools", help="comma list of " + ",".join(TOOLS) + " (default: the ones installed)")
    p.add_argument("--home", default=os.path.expanduser("~"), help="install into another home (for testing)")
    p.add_argument("--adopt", action="store_true",
                   help="move skills installed straight into a tool (e.g. ~/.claude/skills) into a layer (--layer)")
    p.add_argument("--layer", default="core", help="layer that --adopt moves skills into (a folder name; created if new)")
    p.add_argument("--only", help="comma list of layers to install (core is always included)")
    p.add_argument("--with", dest="with_", help="comma list of layers to add to the saved profile")
    p.add_argument("--uninstall", help="comma list of layers to remove from the tools (with a backup)")
    p.add_argument("--layers-dir", action="append", default=[], metavar="DIR",
                   help="folder that holds more layers (e.g. a private repo); remembered in the profile, repeatable")
    p.add_argument("--build", default=BUILD, help="where to render the composed AGENTS.md and policy.json (for testing)")
    args = p.parse_args()
    if not layerlib.valid_name(args.layer):
        sys.exit(f"--layer {args.layer}: invalid name (lowercase letters, digits, - and _; not 'adapters', 'docs', 'tests', 'build').")
    BUILD = os.path.abspath(args.build)
    HOME = os.path.abspath(args.home)
    layerlib.use_layers_dirs(args.layers_dir, HOME)
    tools = args.tools.split(",") if args.tools else detected()
    unknown = set(tools) - set(TOOLS)
    if unknown:
        sys.exit(f"unknown tools: {', '.join(sorted(unknown))}")
    if args.uninstall:
        print(f"ai-setup: {ROOT}\nhome: {HOME}\ntools: {', '.join(tools) or 'none found'}")
        run_uninstall(tools)
        print("\ndone." + (" (nothing changed: this was a dry run)" if args.dry_run else ""))
        return
    SELECTED[:] = resolve_layers()
    problems = lint_policy(policy())
    if problems:
        sys.exit("the composed policy has problems, nothing was installed:\n  " + "\n  ".join(problems))
    print(f"ai-setup: {ROOT}\nhome: {HOME}\ntools: {', '.join(tools) or 'none found'}\nlayers: {', '.join(SELECTED)}\n")
    agents_md = build_agents_md()
    build_policy()
    link_notes(SELECTED)
    for tool in tools:
        print(f"\n== {tool}")
        globals()["install_" + tool](agents_md)
    save_profile()
    if UNMANAGED:
        print("\n⚠ Skills installed outside ai-setup (not in the backup, not shared with the other tools):")
        print("\n".join("  " + p for p in UNMANAGED))
        print("  → ./install.sh --adopt [--layer name] to bring them into ai-setup, or reinstall them with ./add-skill.sh <url>")
    print("\ndone." + (" (nothing changed: this was a dry run)" if args.dry_run else ""))


if __name__ == "__main__":
    main()
